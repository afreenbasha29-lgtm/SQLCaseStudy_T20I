-- find the team with the most wins when chasing a target (wins by wickets)
SELECT WINNER, CHASING_WINS FROM (
SELECT WINNER, COUNT(*) AS CHASING_WINS,
RANK() OVER(ORDER BY COUNT(*) DESC) AS RK
FROM T20I 
WHERE MARGIN LIKE '%WICKETS' 
AND
WINNER NOT IN ('TIED' , 'NO RESULT')
GROUP BY WINNER
ORDER BY CHASING_WINS DESC) T
WHERE RK = 1;

