-- identify the month in 2024 in which the highest number of T20 matches were played
SELECT MONTH(MATCHDATE) AS MONTH_NO, MONTHNAME(MATCHDATE)AS MONTH_NAME, COUNT(*) AS MATCHES_PLAYED
FROM T20I
WHERE YEAR(MATCHDATE) = 2024
GROUP BY MONTH(MATCHDATE), MONTHNAME(MATCHDATE)
ORDER BY MATCHES_PLAYED DESC;

-- for each team find how many matches they played in 2024 and their winning percentage
WITH COMBINED_TEAMS AS (
SELECT TEAM1 AS TEAM 
FROM T20I 
WHERE YEAR(MATCHDATE) = 2024
UNION ALL
SELECT TEAM2 AS TEAM 
FROM T20I 
WHERE YEAR(MATCHDATE) = 2024),

MATCHES_PLAYED AS(
SELECT TEAM, COUNT(*) AS MATCHES_PLAYED
FROM COMBINED_TEAMS
GROUP BY TEAM
),

TEAM_WINS AS (
SELECT WINNER AS TEAM,
COUNT(*) AS WINS
FROM T20I 
WHERE YEAR(MATCHDATE) = 2024
AND WINNER NOT IN ('TIED', 'NO RESULT')
GROUP BY WINNER)

SELECT M.TEAM, 
M.MATCHES_PLAYED,
W.WINS AS WINS,
ROUND(W.WINS * 100.0 / M.MATCHES_PLAYED , 2) AS WINNING_PERCENTAGE
FROM MATCHES_PLAYED M
LEFT JOIN TEAM_WINS W 
ON M.TEAM = W.TEAM
ORDER BY WINNING_PERCENTAGE DESC;

