USE T20ICRICKET;

SELECT 
    *
FROM
    T20I;

-- identify matches played between 2 specific teams in 2024 and their results(eg : india and south africa)

SELECT 
    TEAM1, TEAM2, WINNER, MATCHDATE
FROM
    T20I
WHERE
    (TEAM1 = 'INDIA'
        AND TEAM2 = 'SOUTH AFRICA')
        OR (TEAM1 = 'SOUTH AFRICA'
        AND TEAM2 = 'INDIA')
        AND YEAR(MATCHDATE) = 2024
ORDER BY MATCHDATE;

-- find the team with the highest number of wins in 2024 and the total matches it won. 
SELECT 
    WINNER,
    COUNT(*) AS NO_OF_WINS,
    YEAR(MATCHDATE) AS YEAR_OF_WIN
FROM
    T20I
WHERE
    YEAR(MATCHDATE) = 2024
GROUP BY WINNER , YEAR_OF_WIN
ORDER BY NO_OF_WINS DESC;

-- rank the teams based on the total number of wins in 2024
SELECT WINNER, NO_OF_WINS,
ROW_NUMBER() OVER(ORDER BY NO_OF_WINS DESC) AS WINNER_RANK
FROM
(
	SELECT WINNER, COUNT(*) AS NO_OF_WINS
    FROM T20I 
    WHERE YEAR(MATCHDATE) = 2024 AND WINNER NOT IN ('TIED', 'NO RESULT')
    GROUP BY WINNER
) t;

SELECT WINNER, COUNT(*) AS NO_OF_WINS,
DENSE_RANK() OVER(ORDER BY COUNT(*) DESC) AS WINNER_RANK
FROM T20I 
WHERE YEAR(MATCHDATE) = 2024 AND WINNER NOT IN('TIED', 'NO RESULT')
GROUP BY WINNER;

